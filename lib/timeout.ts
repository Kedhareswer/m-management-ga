/** Reject if a promise doesn't settle in time — used to guard disk writes
 * so a hung filesystem (network mount, sandboxed fs) degrades to the
 * in-memory fallback instead of freezing every request behind it. */
export function withTimeout<T>(promise: Promise<T>, ms: number, label: string): Promise<T> {
  return new Promise<T>((resolve, reject) => {
    const timer = setTimeout(() => reject(new Error(`${label} timed out after ${ms}ms`)), ms);
    promise.then(
      (v) => {
        clearTimeout(timer);
        resolve(v);
      },
      (e) => {
        clearTimeout(timer);
        reject(e);
      }
    );
  });
}
